"""Bounding ALL small-norm cancellations, not just the cheapest one.

THE OPEN QUESTION, MADE CONCRETE
--------------------------------
`zeta_cancellation.py` showed the cheapest cancellation (unit deviation on
one account, d_0 = -zeta*d_1) is inflated to the challenge's peak
coefficient and so fails a tight norm gate. It left the real question open:
bound ALL small-norm solutions of

    sum_i zeta^i d_i = 0   in R_q.

That is not a vague worry -- it is a shortest-vector problem, and therefore
computable. For S = 2 the solution set is exactly

    L = { (-zeta*d mod q, d) : d in R_q }

which is a LATTICE of dimension 2n (n integer coefficients for each of
d_0, d_1) and determinant q^n: the map d -> (-zeta*d, d) is injective and
its image has index q^n in Z^{2n}. So the question "does any small
cancellation exist?" is "what is the shortest nonzero vector of L?".

THE BOUND -- AND WHY IT IS WRONG
--------------------------------
The Gaussian heuristic predicts

    lambda_1(L) ~ sqrt(dim / (2*pi*e)) * det^(1/dim)
                = sqrt(2n / (2*pi*e)) * sqrt(q).

The sqrt(q) term looks decisive: for q = 2^49 it is ~2^24.5 against a
single-digit norm budget. That argument is REFUTED by brute force.

Measured shortest cancellation vs the heuristic, sparse zeta with p = 2:

    n    q        GH est   brute   ratio
    4      97       6.74       2    0.30
    4     257      10.97       2    0.18
    4     769      18.98       2    0.11
    4    3329      39.49       2    0.05
    4   12289      75.87       2    0.03
    8      97       9.53       2    0.21
    8   12289     107.30       2    0.02

The brute-force minimum is 2 at EVERY modulus -- flat across a 127x range
of q, while the heuristic grows as sqrt(q). Inspecting the witness shows
why:

    zeta   = (-2,  0,  0, -2)
    d      = (-2, -1,  0,  1)
    -zeta*d = (-2, -2, -2, -2)      ||.||_inf = 2

identical at q = 97 and q = 12289. The product is small OVER THE INTEGERS;
no modular reduction happens at all. The determinant argument assumed the
modulus constrains the solution set, but a cancellation that never wraps
lives in the integer lattice generated by the challenge, where q plays no
role. The lattice is q-ary only for vectors large enough to reduce, and the
shortest vectors are not.

So `LatticeBound` is retained ONLY as the refuted hypothesis, clearly
labelled. The correct statement is below.

WHAT ACTUALLY BOUNDS CANCELLATIONS
----------------------------------
The real quantity is the shortest vector of the INTEGER lattice
{ (-zeta*d, d) : d in Z[x]/(x^n+1) }, unreduced. Multiplication by zeta is
a linear map whose matrix is the negacyclic circulant of zeta, so the
question is the smallest ||(-C_zeta d, d)||_inf over nonzero integer d --
which depends on the geometry of C_zeta, NOT on q.

For a sparse zeta with peak coefficient p, taking d a signed unit vector
gives norm p (the earlier peak-coefficient finding). The brute force shows
one can sometimes do better than p by spreading d, but on these instances
never below p itself: the minimum found equals p = 2 in every row above.
That is consistent with -- though not a proof of -- the bound

    shortest cancellation >= 1, and empirically = p for sparse zeta,

which means the aggregate check's soundness margin is the ratio between the
challenge peak p and the verifier's norm budget. For the paper's profile
p = 8, so a budget below 8 blocks all cancellations found here.

This is a much weaker and much more contingent statement than sqrt(q), and
it is the honest one.

HONEST LIMITS
-------------
1. The Gaussian heuristic is a HEURISTIC. It is accurate for random
   lattices and this lattice is structured (it is a module over R_q), so
   the true lambda_1 can deviate. `exhaustive_shortest` therefore verifies
   it by brute force at tiny n, where exhaustive search is feasible.
2. A structured lattice can have unusually short vectors if the challenge
   is degenerate -- e.g. a zeta that is a zero divisor, or one with a small
   inverse. `degenerate_challenge_check` tests for that case explicitly
   rather than assuming genericity.
3. This covers S = 2. For S > 2 the lattice has dimension (S)n and the same
   determinant argument gives sqrt-of-q growth with a larger dimension
   factor, so the bound only improves; that is argued, not computed here.
"""

from __future__ import annotations

import itertools
import math
from dataclasses import dataclass

from .hmc import bounded_ring_element, centered_coefficients
from .ring_commitment import RingElement, ToyParameters


class BoundError(ValueError):
    """Malformed cancellation-bound input."""


@dataclass(frozen=True)
class LatticeBound:
    """REFUTED HYPOTHESIS -- kept for the record, not for use.

    Predicts the shortest cancellation as the Gaussian heuristic of the
    q-ary lattice {(-zeta*d, d)}. Brute force showed the true minimum is
    flat in q (always the challenge peak p) because the shortest
    cancellations never wrap modulo q, so the determinant plays no role.
    Ratios measured as low as 0.02.

    `refuted` is True by construction so no caller can mistake this for a
    live bound.
    """

    ring_degree: int
    modulus: int
    accounts: int
    refuted: bool = True

    @property
    def dimension(self) -> int:
        """One block of n integer coefficients per account."""
        return self.accounts * self.ring_degree

    @property
    def log2_determinant(self) -> float:
        """det = q^n: the image of d -> (-zeta*d, d) has index q^n."""
        return self.ring_degree * math.log2(self.modulus)

    @property
    def gaussian_heuristic(self) -> float:
        """sqrt(dim / (2*pi*e)) * det^(1/dim)."""
        dimension = self.dimension
        root_determinant = 2.0 ** (self.log2_determinant / dimension)
        return math.sqrt(dimension / (2.0 * math.pi * math.e)) \
            * root_determinant

    @property
    def log2_gaussian_heuristic(self) -> float:
        return math.log2(self.gaussian_heuristic)

    def exceeds_budget(self, norm_budget: float) -> bool:
        return self.gaussian_heuristic > norm_budget

    def summary(self, norm_budget: float = 1.0) -> dict:
        return {
            "ring_degree": self.ring_degree,
            "modulus": self.modulus,
            "accounts": self.accounts,
            "lattice_dimension": self.dimension,
            "log2_determinant": round(self.log2_determinant, 1),
            "shortest_cancellation_estimate": round(
                self.gaussian_heuristic, 2
            ),
            "log2_shortest": round(self.log2_gaussian_heuristic, 2),
            "norm_budget": norm_budget,
            "budget_exceeded": self.exceeds_budget(norm_budget),
            "margin_bits": round(
                self.log2_gaussian_heuristic - math.log2(max(norm_budget, 1)),
                2,
            ),
        }


def paper_bound(accounts: int = 2) -> LatticeBound:
    """The paper's profile: d = 64, q = 2^49 - 2^18 + 2^9 + 1."""
    return LatticeBound(
        ring_degree=64,
        modulus=2 ** 49 - 2 ** 18 + 2 ** 9 + 1,
        accounts=accounts,
    )


def _negacyclic_multiply(left, right, n: int, q: int) -> tuple:
    """(left * right) in Z_q[x]/(x^n + 1), on plain integer tuples."""
    out = [0] * n
    for i, a in enumerate(left):
        if a == 0:
            continue
        for j, b in enumerate(right):
            if b == 0:
                continue
            index = i + j
            if index < n:
                out[index] = (out[index] + a * b) % q
            else:
                out[index - n] = (out[index - n] - a * b) % q
    return tuple(out)


def _centered(values, q: int) -> tuple:
    half = q // 2
    return tuple(v - q if v > half else v for v in values)


def exhaustive_shortest(zeta_coeffs, n: int, q: int,
                        search_radius: int = 1) -> dict:
    """Brute-force the shortest cancellation, to check the heuristic.

    Enumerates every d with coefficients in [-search_radius, search_radius]
    and measures max(||-zeta*d||_inf, ||d||_inf). Only feasible for tiny n
    and radius -- the point is to confirm the Gaussian heuristic is not
    wildly wrong on this STRUCTURED lattice, where it could in principle
    fail.

    Excludes d = 0, which gives the trivial all-zero cancellation.
    """
    if n <= 0 or q <= 1:
        raise BoundError("need n > 0 and q > 1")
    if search_radius < 1:
        raise BoundError("search_radius must be at least 1")
    if (2 * search_radius + 1) ** n > 3_000_000:
        raise BoundError(
            f"search space {(2 * search_radius + 1) ** n} too large; "
            "lower n or search_radius"
        )

    best_norm = None
    best_d = None
    values = range(-search_radius, search_radius + 1)

    for candidate in itertools.product(values, repeat=n):
        if all(value == 0 for value in candidate):
            continue
        reduced = tuple(value % q for value in candidate)
        product = _negacyclic_multiply(zeta_coeffs, reduced, n, q)
        forced = _centered(product, q)
        norm = max(
            max(abs(value) for value in candidate),
            max(abs(value) for value in forced),
        )
        if best_norm is None or norm < best_norm:
            best_norm = norm
            best_d = candidate

    return {
        "searched_radius": search_radius,
        "shortest_found": best_norm,
        "witness_d": best_d,
        "note": (
            "brute force over ||d||_inf <= radius; the true lambda_1 could "
            "be smaller only if it needs coefficients outside that radius, "
            "which would make it LARGER in the d block, so this is a valid "
            "upper bound on the minimum over this box"
        ),
    }


def degenerate_challenge_check(zeta: RingElement) -> dict:
    """Is this challenge degenerate enough to admit a cheap cancellation?

    The bound assumes a generic challenge. Two degeneracies would break it:
    a zeta that is a zero divisor (then zeta*d = 0 for some small d, giving
    a cancellation of norm ||d||), or a zeta with an unusually small
    inverse. Testing for the first directly: search small d for zeta*d = 0.
    """
    params = zeta.params
    n, q = params.n, params.q
    zeta_coeffs = tuple(zeta.coeffs)

    annihilators = []
    for position in range(n):
        for value in (1, -1, 2, -2):
            coeffs = [0] * n
            coeffs[position] = value % q
            product = _negacyclic_multiply(zeta_coeffs, tuple(coeffs), n, q)
            if all(entry == 0 for entry in product):
                annihilators.append((position, value))

    return {
        "zero_divisor_found": bool(annihilators),
        "annihilators": annihilators[:4],
        "verdict": (
            "DEGENERATE: zeta annihilates a unit-norm element, so a "
            "cancellation of norm 1 exists and the aggregate check is void "
            "for this challenge"
            if annihilators else
            "non-degenerate against unit and norm-2 monomials: no trivial "
            "annihilator, so the lattice bound is not defeated this way"
        ),
    }


def assessment(norm_budget: float = 1.0, accounts: int = 2) -> dict:
    """The corrected finding for the paper's profile.

    Reports the refuted heuristic alongside the measured behaviour, because
    the refutation is the substantive result: it moves the soundness margin
    from sqrt(q) (~2^24.5, comfortable) to the challenge peak p (= 8 for
    the paper's profile, contingent on the norm budget).
    """
    bound = paper_bound(accounts)
    heuristic = bound.summary(norm_budget)
    challenge_peak = 8          # paper profile (d, w, p) = (64, 56, 8)

    return {
        "refuted_heuristic": heuristic,
        "refutation": (
            "The q-ary Gaussian heuristic predicts "
            f"2^{heuristic['log2_shortest']:.1f} but brute force finds the "
            "shortest cancellation is the challenge peak p at EVERY "
            "modulus tested (97 through 12289, a 127x range), because the "
            "witness never wraps mod q: zeta=(-2,0,0,-2), d=(-2,-1,0,1), "
            "-zeta*d=(-2,-2,-2,-2). Measured ratios fell to 0.02, so the "
            "determinant argument does not apply."
        ),
        "corrected_margin": {
            "shortest_cancellation": challenge_peak,
            "basis": "challenge peak coefficient p, measured not derived",
            "norm_budget": norm_budget,
            "blocked": challenge_peak > norm_budget,
            "margin_factor": round(challenge_peak / max(norm_budget, 1e-9), 2),
        },
        "consequence": (
            "The aggregate check's soundness under known zeta rests on the "
            f"ratio p/budget = {challenge_peak}/{norm_budget}, not on a "
            "sqrt(q) gap. That is a small, parameter-dependent margin: any "
            "design whose verifier norm budget reaches p loses the "
            "aggregate check entirely once zeta is public."
        ),
        "residual_gaps": (
            "1) Brute force covers n <= 8 and radius <= 3; the true minimum "
            "for the paper's n = 64 is unmeasured and could be BELOW p. "
            "2) No proof that p is a lower bound -- only that no smaller "
            "cancellation was found in a small box. 3) A reduction "
            "algorithm (LLL/BKZ on the negacyclic circulant) would give a "
            "far better answer than exhaustive search and has not been run."
        ),
        "status": (
            "NOT RESOLVED, and now known to be WORSE than the previous "
            "module suggested. The 320-bit round reduction should not be "
            "banked on this: it needs the circulant lattice reduced at the "
            "real parameters by someone who does this professionally."
        ),
    }


